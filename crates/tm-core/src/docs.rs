//! The two files a reviewer reads before anything else.
//!
//! Reviewers start with no context, so everything they need to judge a change is written
//! down: `ARCHITECTURE.md` says how the app is meant to fit together, `CHANGES.md` says what
//! changed recently. A break shows up as a recent change that contradicts the architecture.
//! Both are generated from the plan and the run's records, so they cannot drift from the code.

use std::collections::BTreeMap;
use std::fmt::Write;

use crate::types::{ChangeEntry, ChangeKind, Plan, ReviewScope};

pub const ARCHITECTURE_FILE: &str = ".taskmaster/ARCHITECTURE.md";
pub const CHANGES_FILE: &str = ".taskmaster/CHANGES.md";

pub fn render_architecture(plan: &Plan) -> String {
    let mut out = String::from("# Architecture\n\nGenerated by Taskmaster from the locked plan. Do not edit.\n");

    out.push_str("\n## Pages\n\n| Page | Route | Owns | Cites |\n|---|---|---|---|\n");
    for p in &plan.pages {
        let cites = if p.cites.is_empty() { "-".to_string() } else { p.cites.join(", ") };
        let _ = writeln!(out, "| {} | `{}` | `{}` | {} |", p.id, p.route, p.owned_glob, cites);
    }

    out.push_str("\n## Contracts\n\nShared code every page imports. Only the Taskmaster changes these.\n\n");
    for c in &plan.contracts {
        let _ = writeln!(out, "- `{}`", c.path);
    }
    if plan.contracts.is_empty() {
        out.push_str("- none\n");
    }

    out.push_str("\n## Connections\n\nEach Dictionary entry and the pages that depend on it.\n\n");
    let mut consumers: BTreeMap<&str, Vec<&str>> = BTreeMap::new();
    for p in &plan.pages {
        for key in &p.cites {
            consumers.entry(key).or_default().push(&p.id);
        }
    }
    for (key, pages) in &consumers {
        let _ = writeln!(out, "- `{key}` is used by {}", pages.join(", "));
    }
    if consumers.is_empty() {
        out.push_str("- none\n");
    }

    out.push_str(
        "\n## Rules\n\n\
         - A page's worker changes only the files its page owns.\n\
         - Pages talk to each other only through contracts and routes, never by importing each other.\n\
         - Dictionary entries are immutable; a change is a new version, and every page citing it is rebuilt.\n",
    );
    out
}

/// The most recent `limit` changes, newest first.
pub fn render_changes(entries: &[ChangeEntry], limit: usize) -> String {
    let mut out = String::from("# Recent changes\n\nGenerated by Taskmaster. Newest first.\n");
    for e in entries.iter().rev().take(limit) {
        let kind = match e.kind {
            ChangeKind::ContractsLocked => "contracts locked",
            ChangeKind::SharedRepaired => "shared files repaired",
            ChangeKind::PageBuilt => "page built",
            ChangeKind::PageRepaired => "page repaired",
            ChangeKind::EntryAmended => "entry amended",
            ChangeKind::ReviewFinding => "review finding",
            ChangeKind::VerifyFailed => "verify failed",
        };
        let _ = write!(out, "\n## {} · {kind}", e.at);
        if let Some(page) = &e.page {
            let _ = write!(out, " · {page}");
        }
        let _ = writeln!(out, "\n\n{}\n", e.summary);
        if let Some(commit) = &e.commit {
            let _ = writeln!(out, "- commit: `{commit}`");
        }
        if let Some(model) = &e.model {
            let _ = writeln!(out, "- by: {model}");
        }
        if !e.keys.is_empty() {
            let _ = writeln!(out, "- entries: {}", e.keys.join(", "));
        }
        if !e.files.is_empty() {
            let _ = writeln!(out, "- files: {}", e.files.join(", "));
        }
    }
    if entries.is_empty() {
        out.push_str("\nNo changes yet.\n");
    }
    out
}

/// The brief for one reviewer. It names the files to read first, because the reviewer
/// knows nothing else about the project.
pub fn review_brief(scope: &ReviewScope) -> String {
    format!(
        "You are reviewing one connection in this project. You cannot edit anything.\n\n\
         Read `{ARCHITECTURE_FILE}` and `{CHANGES_FILE}` first. The first says how the app is meant \
         to fit together; the second says what changed recently.\n\n\
         Connection under review: Dictionary entry `{key}`, used by pages: {pages}.\n\
         Cite `{key}` from the Dictionary, then read how each of those pages uses it.\n\n\
         Look for, in this order: a recent change that contradicts the architecture; the entry \
         being used differently from how it is defined; logic duplicated across these pages; \
         obvious performance problems. Ignore style. The compiler has already passed, so do not \
         report type errors.\n\n\
         Reply with only a JSON array. Each item: {{\"page\", \"file\", \"line\", \"failure\"}}, where \
         `failure` states the input or state that goes wrong and what happens. Report nothing you \
         cannot point to a line for. An empty array means the connection is sound.",
        key = scope.key,
        pages = scope.consumers.join(", "),
    )
}

/// The brief for the one reviewer per run that looks only for security problems.
pub fn security_brief(pages: &[String]) -> String {
    format!(
        "You are reviewing this project for security problems only. You cannot edit anything.\n\n\
         Read `{ARCHITECTURE_FILE}` and `{CHANGES_FILE}` first.\n\n\
         Pages to check: {pages}.\n\n\
         Look for: user input reaching HTML, a query, a file path or a redirect unchecked; data \
         shown or changed without the access check the contracts require; secrets or tokens in \
         client code; routes that trust an id from the request. Ignore everything else.\n\n\
         Reply with only a JSON array. Each item: {{\"page\", \"file\", \"line\", \"failure\"}}, where \
         `failure` states what an attacker sends and what they gain. An empty array means you \
         found nothing.",
        pages = pages.join(", "),
    )
}

/// The brief for the agent that checks one finding before any worker is asked to fix it.
pub fn verify_brief(finding: &crate::types::Finding) -> String {
    format!(
        "Another reviewer reported a problem. Decide whether it is real. You cannot edit anything.\n\n\
         Claim: in `{file}` at line {line} (page {page}): {failure}\n\n\
         Read that file and whatever it depends on. Try to disprove the claim: check whether the \
         code already handles the case, whether the line says what the claim says, and whether \
         the failure can actually happen.\n\n\
         Reply with only `{{\"real\": true}}` or `{{\"real\": false, \"why\": \"...\"}}`. If you are \
         unsure, answer false.",
        file = finding.file,
        line = finding.line,
        page = finding.page,
        failure = finding.failure,
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::types::{ContractFile, Estimate, PagePlan};

    fn plan() -> Plan {
        let page = |id: &str, cites: &[&str]| PagePlan {
            id: id.into(),
            route: format!("/{id}"),
            owned_glob: format!("app/{id}/**"),
            cites: cites.iter().map(|c| c.to_string()).collect(),
            brief: String::new(),
            done: String::new(),
            units: vec![],
            skills: vec![],
        };
        Plan {
            contracts: vec![ContractFile { path: "contracts/types.ts".into(), content: String::new() }],
            pages: vec![page("dashboard", &["auth", "nav"]), page("settings", &["auth"])],
            estimate: Estimate { tokens: 0, usd: 0.0 },
            design: String::new(),
        }
    }

    #[test]
    fn architecture_lists_pages_contracts_and_connections() {
        let doc = render_architecture(&plan());
        assert!(doc.contains("| dashboard | `/dashboard` | `app/dashboard/**` | auth, nav |"));
        assert!(doc.contains("- `contracts/types.ts`"));
        assert!(doc.contains("- `auth` is used by dashboard, settings"));
        assert!(doc.contains("- `nav` is used by dashboard"));
        // Same plan, same file: the document is safe to regenerate on every run.
        assert_eq!(doc, render_architecture(&plan()));
    }

    #[test]
    fn changes_are_newest_first_and_limited() {
        let entry = |at: &str, summary: &str| ChangeEntry {
            at: at.into(),
            kind: ChangeKind::PageRepaired,
            page: Some("settings".into()),
            commit: Some("abc1234".into()),
            model: Some("gemini-3.8-flash".into()),
            files: vec!["app/settings/page.tsx".into()],
            keys: vec!["auth".into()],
            summary: summary.into(),
        };
        let log = [entry("t1", "alpha"), entry("t2", "bravo"), entry("t3", "charlie")];
        let doc = render_changes(&log, 2);
        assert!(doc.find("charlie").unwrap() < doc.find("bravo").unwrap());
        assert!(!doc.contains("alpha"));
        assert!(doc.contains("## t3 · page repaired · settings"));
        assert!(doc.contains("- commit: `abc1234`") && doc.contains("- entries: auth"));
        assert!(render_changes(&[], 5).contains("No changes yet."));
    }

    #[test]
    fn review_brief_points_a_cold_reviewer_at_both_files() {
        let scope = ReviewScope { key: "auth".into(), consumers: vec!["dashboard".into(), "settings".into()] };
        let brief = review_brief(&scope);
        assert!(brief.contains(ARCHITECTURE_FILE) && brief.contains(CHANGES_FILE));
        assert!(brief.contains("`auth`") && brief.contains("dashboard, settings"));
        assert!(brief.contains("cannot edit"));
    }
}
